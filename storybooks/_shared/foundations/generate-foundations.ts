/**
 * Generates the "Foundations" pages of the composition Storybook
 * from `packages/foundations/docs/*.md`. The test table is generated at build
 * time by generate-test-table.ts, because it follows the test files.
 *
 * Every page imports its Markdown file with `?raw`, so a change in the docs
 * shows up without running this script again. The script only has to run when
 * a docs file is added or renamed (edit `PAGES` below).
 *
 * The docs were written for the Patternhub and link to its routes
 * (`./color-schemes`, `../densities/readme`). `links.ts` rewrites those links
 * at render time: to the Storybook page, to the Design System Platform, or to
 * the Patternhub as long as there is no other place for the content yet.
 *
 * Usage: node storybooks/_shared/foundations/generate-foundations.ts
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { PAGES } from './pages.ts';

const STORYBOOKS = resolve(import.meta.dirname, '..', '..');

const OUT = join(STORYBOOKS, '_storybook/src/foundations');

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

for (const page of PAGES) {
	const platform = page.platform
		? `\n\n> **Design:** ${page.platform.text} [${page.platform.label} on the Design System Platform](${page.platform.url}).`
		: '';
	const learn = page.learn
		? `\n\n> **Learn:** [${page.learn.title}](https://design-system.deutschebahn.com/documentation/learn/${page.learn.slug}) on the Design System Platform.`
		: '';
	// Interactive examples: every story of the stories file, with its JSDoc
	// comment as the description.
	const stories = page.examples
		? [
				...readFileSync(
					join(
						STORYBOOKS,
						'_storybook/src/foundations-examples',
						`${page.examples.file}.stories.tsx`
					),
					'utf8'
				).matchAll(/^export const (\w+): Story/gm)
			].map((match) => match[1])
		: [];
	const examples =
		stories.length > 0
			? `\n## Examples\n\n${stories
					.map(
						(story) =>
							`### ${story.replaceAll(/(?<=[a-z])(?=[A-Z])/g, ' ')}\n\n<Description of={Examples.${story}} />\n\n<Canvas of={Examples.${story}} />`
					)
					.join('\n\n')}\n`
			: '';
	const mdx = `import { ${stories.length > 0 ? 'Canvas, Description, ' : ''}Markdown, Meta } from "@storybook/addon-docs/blocks";
import Doc from "../../../../${page.source}?raw";
import { rewriteDocsLinks } from "../../../_shared/foundations/links";${stories.length > 0 ? `\nimport * as Examples from "../foundations-examples/${page.examples?.file}.stories";` : ''}

{/* Generated by storybooks/_shared/foundations/generate-foundations.ts – do not edit. Source: ${page.source} */}

<Meta title="Foundations/${page.title}" />${platform}${learn}

<Markdown>{rewriteDocsLinks(Doc, "${page.route}")}</Markdown>
${examples}
_Source: [${page.source}](https://github.com/db-ux-design-system/core-web/blob/main/${page.source})_
`;
	const target = join(OUT, `${page.id}.mdx`);
	writeFileSync(target, mdx);
	console.log(
		`[foundations] wrote ${target.replace(`${STORYBOOKS}/`, 'storybooks/')}`
	);
}
