const GENERATED_NOTE =
	'{/* Generated by storybooks/_shared/overview/generate-overviews.ts – do not edit. */}';

const read = (path: string): string => readFileSync(path, 'utf8');

const write = (path: string, content: string): void => {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, content);
	console.log(`[overviews] wrote ${path.replace(`${ROOT}/`, '')}`);
};

const pascal = (value: string): string =>
	value.replaceAll(/(^|[-_ ])(\w)/g, (_, __, char: string) =>
		char.toUpperCase()
	);

const escapeCell = (value: string): string =>
	value
		.replaceAll(/\s*\n\s*/g, ' ')
		.replaceAll('|', String.raw`\|`)
		.replaceAll(/[{}<>]/g, (char) => `&#${char.codePointAt(0)};`);

type ExampleGroup = {
	file: string;
	title: string;
	id: string;
	stories: string[];
};

/** Story groups of a component, read from the generated example stories. */
const getExamples = (name: string, storybook: string): ExampleGroup[] => {
	const dir = join(STORYBOOKS, storybook, 'src/components', name, 'examples');
	if (!existsSync(dir)) {
		throw new Error(
			`[overviews] ${dir} is missing – run generate:stories first`
		);
	}
	return readdirSync(dir)
		.filter((file) => /\.example\.stories\.tsx?$/.test(file))
		.map((file) => {
			const source = read(join(dir, file));
			const title = /title:\s*'[^']*\/([^'/]+)'/.exec(source)?.[1];
			if (!title) {
				throw new Error(`[overviews] no title in ${file}`);
			}
			const stories = [
				...source.matchAll(/^export const (\w+): Story/gm)
			].map((match) => match[1]);
			const id = title.toLowerCase().replaceAll(/\s+/g, '-');
			return { file: file.replace(/\.tsx?$/, ''), title, id, stories };
		})
		.toSorted((a, b) =>
			a.id === 'variant'
				? -1
				: b.id === 'variant'
					? 1
					: a.title.localeCompare(b.title)
		);
};

type WebTypesProperty = { name: string; description?: string; type?: string };
type WebTypesElement = {
	name: string;
	attributes?: Array<{
		name: string;
		description?: string;
		value?: { type?: string };
	}>;
	js?: { properties?: WebTypesProperty[] };
};

const getWebTypes = (name: string): WebTypesElement => {
	const path = join(ROOT, 'output/stencil/dist/web-types.json');
	if (!existsSync(path)) {
		throw new Error(
			`[overviews] ${path} is missing – build the outputs first`
		);
	}
	const webTypes = JSON.parse(read(path)) as {
		contributions: { html: { elements: WebTypesElement[] } };
	};
	const element = webTypes.contributions.html.elements.find(
		(entry) => entry.name === `db-${name}`
	);
	if (!element) {
		throw new Error(`[overviews] db-${name} not in web-types`);
	}
	return element;
};

/** Attributes that are internal or covered by the native `id`/`class`. */
const SKIPPED_ATTRIBUTES = new Set(['id', 'prop-overrides', 'classname']);

/**
 * HTML attributes of the root element, read from the component source:
 * `data-*` attributes and native attributes, each with the props that set it.
 */
const getHtmlAttributes = (name: string, webTypes: WebTypesElement): string => {
	const source = read(
		join(
			ROOT,
			'packages/components/src/components',
			name,
			`${name}.lite.tsx`
		)
	);
	const jsx = source.slice(source.lastIndexOf('return ('));
	const root = /<[a-z]+\s([\s\S]*?)>\s*\n/.exec(jsx)?.[1] ?? '';
	const properties = new Map(
		(webTypes.js?.properties ?? []).map((prop) => [prop.name, prop])
	);

	const rows: string[] = [];
	for (const match of root.matchAll(/(?:^|\n)\s*([a-z-]+)=\{/gi)) {
		const attribute = match[1];
		if (['ref', 'id', 'class', 'type'].includes(attribute)) {
			continue;
		}
		const start = (match.index ?? 0) + match[0].length;
		const next = root.slice(start).search(/\n\s*[a-z-]+=\{/i);
		const value =
			next === -1 ? root.slice(start) : root.slice(start, start + next);
		const props = [
			...new Set(
				[...value.matchAll(/props\.(\w+)/g)].map((prop) => prop[1])
			)
		];
		const first = properties.get(props[0] ?? '');
		const isData = attribute.startsWith('data-');
		const isBoolean = value.includes('getBoolean');
		// Framework-only types (e.g. `any` for a React form action) are a string in HTML.
		const type =
			!first?.type || first.type === 'any' ? 'string' : first.type;
		const values = isBoolean
			? isData
				? '`true` \\| `false`'
				: 'boolean attribute (present or absent)'
			: `\`${escapeCell(type)}\``;
		rows.push(
			`| \`${attribute.toLowerCase()}\` | ${values} | ${escapeCell(first?.description ?? '')} |`
		);
	}
	const typeProp = properties.get('type');
	rows.unshift(
		`| \`type\` | \`${escapeCell(typeProp?.type ?? 'string')}\` | ${escapeCell(typeProp?.description ?? '')} Without it, the browser uses \`submit\`. |`
	);
	return [
		'| Attribute | Values | Description |',
		'| --- | --- | --- |',
		...rows
	].join('\n');
};

/** Attributes of the custom element, from the web-types. */
const getWebComponentAttributes = (webTypes: WebTypesElement): string => {
	const rows = (webTypes.attributes ?? [])
		.filter((attribute) => !SKIPPED_ATTRIBUTES.has(attribute.name))
		.map(
			(attribute) =>
				`| \`${attribute.name}\` | \`${escapeCell(attribute.value?.type ?? 'string')}\` | ${escapeCell(attribute.description ?? '')} |`
		);
	return [
		'| Attribute | Type | Description |',
		'| --- | --- | --- |',
		...rows
	].join('\n');
};

const docsPath = (name: string, file: string) =>
	`packages/components/src/components/${name}/docs/${file}.md`;

const hasDoc = (name: string, file: string) =>
	existsSync(join(ROOT, docsPath(name, file)));

/**
 * "Guidelines" section with a card to the English platform page of the
 * component (Storybook is English only). Plain `db-card` markup, because the
 * MDX pages of the Angular, Vue and Web Components Storybooks cannot import
 * the React components; the core component CSS is loaded in every Storybook.
 */
const buildGuidelines = (meta: ComponentMeta): string => {
	const name = meta.title.replace(/^DB/, '');
	// Inline styles: the card appears in five Storybooks with different global CSS files.
	// `data-mode="light"`: the Storybook docs page stays light, also when the
	// mode switch sets the stories to dark; the card follows the page.
	return `## Guidelines

How and when to use the component is documented on the Design System Platform:

<div data-mode="light">
<a className="db-card" data-behavior="interactive" data-spacing="small" href="${meta.platformUrl}" target="_blank" rel="noopener noreferrer" style={{ maxInlineSize: '32rem', display: 'flex', flexDirection: 'column', gap: 'var(--db-spacing-fixed-xs)', textDecoration: 'none', color: 'inherit' }}>
	<strong>${name} guidelines</strong>
	<span>When to use it, variants, Do and Don’t, design rules for accessibility.</span>
	<span>Design System Platform ↗</span>
</a>
</div>`;
};

const statusLine = (meta: ComponentMeta): string => {
	const status = meta.status.charAt(0).toUpperCase() + meta.status.slice(1);
	const review = meta.accessibilityReview
		? ` · **Accessibility review:** ${meta.accessibilityReview.status} (${meta.accessibilityReview.date})`
		: '';
	return `**Status:** ${status}${review}`;
};

const buildOverviewMdx = (
	name: string,
	meta: ComponentMeta,
	fw: Framework
): string => {
	const toRoot = '../../../../../';
	const examplesBase =
		fw.examplesFrom === fw.storybook
			? '../../components'
			: `../../../../${fw.examplesFrom}/src/components`;
	const examples = getExamples(name, fw.examplesFrom).filter((group) =>
		existsSync(
			join(
				STORYBOOKS,
				fw.examplesFrom,
				'src/components',
				name,
				'examples',
				`${group.file}.${fw.examplesFrom === 'react-storybook' ? 'tsx' : 'ts'}`
			)
		)
	);

	const blocks = [
		...(fw.api === 'argtypes' ? ['ArgTypes'] : []),
		'Canvas',
		'Markdown',
		'Meta',
		...(meta.requires?.length ? ['Source'] : [])
	];

	const imports = [
		`import { ${blocks.join(', ')} } from "@storybook/addon-docs/blocks";`,
		`import * as OverviewStories from "./${name}.overview.stories";`,
		...examples.map(
			(group) =>
				`import * as ${pascal(group.id)}Stories from "${examplesBase}/${name}/examples/${group.file}";`
		)
	];
	const isAccessibility = hasDoc(name, 'Accessibility');
	if (isAccessibility) {
		imports.push(
			`import Accessibility from "${toRoot}${docsPath(name, 'Accessibility')}?raw";`
		);
	}

	const webTypes = fw.api === 'argtypes' ? undefined : getWebTypes(name);
	const api =
		fw.api === 'argtypes'
			? '## Properties\n\n<ArgTypes of={OverviewStories} />'
			: // MDX here has no GFM tables, the Markdown block has. The table is a
				// JSON string, so no character in it needs MDX escaping.
				fw.api === 'html'
				? `## Attributes\n\nIn HTML the component is a \`<button>\` with the class \`db-${name}\`. Options are \`data-\` attributes next to the native attributes of the element.\n\n<Markdown>{${JSON.stringify(getHtmlAttributes(name, webTypes!))}}</Markdown>`
				: `## Attributes\n\n<Markdown>{${JSON.stringify(getWebComponentAttributes(webTypes!))}}</Markdown>`;

	const sections = [
		imports.join('\n'),
		GENERATED_NOTE,
		'<Meta of={OverviewStories} />',
		`# ${meta.title}`,
		meta.summary,
		statusLine(meta),
		buildGuidelines(meta),
		// The setup is the same for every component of a framework and is
		// documented once on the platform. Only extra packages show up here.
		meta.requires?.length
			? `Set up your project as described in [${fw.setupTitle}](${PLATFORM}/learn/${fw.setup}), plus:\n\n<Source language="shell" dark code="pnpm add ${meta.requires.join(' ')}" />`
			: `Setup: [${fw.setupTitle}](${PLATFORM}/learn/${fw.setup}) on the Design System Platform.`,
		'## Usage',
		fw.api === 'argtypes'
			? 'Open **Show code** below a preview for a snippet you can copy, including the imports. The example pages linked below each group have controls.'
			: 'Open **Show code** below a preview for the markup you can copy, including what it needs to load.'
	];
	// The examples are the usage: "Show code" contains the imports as well
	// (see storybooks/_shared/storybook-config/source-imports.ts), so the
	// handwritten docs/<Framework>.md is not shown here. It stays for npm, the
	// MCP server and the Patternhub.
	for (const group of examples) {
		sections.push(
			`### ${group.title}`,
			group.stories
				.map(
					(story) =>
						`<Canvas of={${pascal(group.id)}Stories.${story}} />`
				)
				.join('\n'),
			`[Open the ${group.title} examples](?path=/docs/components-${meta.title.toLowerCase()}-${group.id}--docs)`
		);
	}
	sections.push(api);
	if (isAccessibility) {
		sections.push(
			'{/* The docs file starts with "## Accessibility"; it is the section heading. */}',
			'<Markdown>{Accessibility}</Markdown>'
		);
	}
	sections.push(
		'## Resources',
		[
			`- [Guidelines on the Design System Platform](${meta.platformUrl})`,
			`- npm: [${fw.npm}](https://www.npmjs.com/package/${fw.npm})`,
			`- [Source code on GitHub](https://github.com/db-ux-design-system/core-web/tree/main/packages/components/src/components/${name})`,
			'- [Changelog](https://github.com/db-ux-design-system/core-web/blob/main/packages/components/CHANGELOG.md)',
			// Migration is documented on the platform. The docs/Migration.md files stay
			// for the MCP server (component migration from DB UI).
			`- Coming from DB UI? [Move from DB UI to Generation 3](${PLATFORM}/learn/migration)`,
			'- Updating across a Major version? [Migration Guides](https://design-system.deutschebahn.com/documentation/releases/migration-guides)'
		].join('\n')
	);
	return `${sections.join('\n\n')}\n`;
};

const ANCHOR_COMMENT = `/*
 * Generated by storybooks/_shared/overview/generate-overviews.ts – do not edit.
 *
 * The overview MDX page needs a CSF file to attach to: it provides the
 * component for the properties table and the TOC parameters. A CSF file needs
 * at least one story, so \`Default\` exists only as that anchor. It is tagged
 * \`!dev\` and not shown anywhere.
 */`;

const TOC = `docs: {
			// The overview structures its sections with h2 (global TOC: h1, h3).
			toc: { headingSelector: 'h2, h3', title: 'Table of Contents' }
		}`;

const buildStories = (
	name: string,
	meta: ComponentMeta,
	fw: Framework,
	firstExample: string
): string => {
	const component = meta.title;
	const title = `Components/${component}/Overview`;
	const tag = `db-${name}`;
	const argTypesImport = `// Generated example stories, reused for the argTypes.
import FirstExample from '../../components/${name}/examples/${firstExample}';`;
	switch (fw.key) {
		case 'react': {
			return `import type { Meta, StoryObj } from '@storybook/react-vite';
import { ${component} } from '@components';
${argTypesImport}

${ANCHOR_COMMENT}
const meta: Meta<typeof ${component}> = {
	title: '${title}',
	component: ${component},
	parameters: {
		${TOC}
	},
	argTypes: FirstExample.argTypes
} satisfies Meta<typeof ${component}>;

export default meta;

export const Default: StoryObj<typeof ${component}> = { tags: ['!dev'] };
`;
		}
		case 'html': {
			return `import type { Meta, StoryObj } from '@storybook/react-vite';
import { ${component} } from '@components';

${ANCHOR_COMMENT}
const meta: Meta<typeof ${component}> = {
	title: '${title}',
	component: ${component},
	parameters: {
		${TOC}
	}
} satisfies Meta<typeof ${component}>;

export default meta;

export const Default: StoryObj<typeof ${component}> = { tags: ['!dev'] };
`;
		}
		case 'angular': {
			return `import type { Meta, StoryObj } from '@storybook/angular';
import { ${component}, type ${component}Props } from '@components';
${argTypesImport}

${ANCHOR_COMMENT}
const meta: Meta<${component}Props> = {
	title: '${title}',
	component: ${component},
	parameters: {
		${TOC}
	},
	argTypes: FirstExample.argTypes
} satisfies Meta<${component}Props>;

export default meta;

export const Default: StoryObj<${component}Props> = {
	tags: ['!dev'],
	render: () => ({ template: '<${tag}></${tag}>' })
};
`;
		}
		case 'vue': {
			return `import type { Meta, StoryObj } from '@storybook/vue3-vite';
import { ${component} } from '@components';
${argTypesImport}

${ANCHOR_COMMENT}
const meta: Meta<typeof ${component}> = {
	title: '${title}',
	component: ${component},
	parameters: {
		${TOC}
	},
	argTypes: FirstExample.argTypes
} satisfies Meta<typeof ${component}>;

export default meta;

export const Default: StoryObj<typeof ${component}> = { tags: ['!dev'] };
`;
		}
		case 'webcomponents': {
			return `import type { Meta, StoryObj } from '@storybook/web-components-vite';
import { html } from 'lit';

${ANCHOR_COMMENT}
const meta: Meta = {
	title: '${title}',
	component: '${tag}',
	parameters: {
		${TOC}
	}
} satisfies Meta;

export default meta;

export const Default: StoryObj = {
	tags: ['!dev'],
	render: () => html\`<${tag}></${tag}>\`
};
`;
		}
		default: {
			throw new Error(`[overviews] unknown framework ${fw.key}`);
		}
	}
};

/**
 * "Getting Started" page of a framework Storybook: a short entry page. The
 * setup itself (installation, styles, DB Theme) is documented once, in the
 * Learn articles of the Design System Platform, and linked from here.
 */
const buildGettingStarted = (fw: Framework): string =>
	[
		'import { Meta } from "@storybook/addon-docs/blocks";',
		GENERATED_NOTE,
		'<Meta title="Getting Started" />',
		`# Getting Started with ${fw.label}`,
		`This Storybook is the technical reference of the ${fw.label} components: every component has an **Overview** page with usage, examples, properties and accessibility, for example **Components → DBButton → Overview**. "Show code" includes the imports, so you can copy an example into a project that is set up.`,
		'## Set up your project',
		`Installation, styles and the first component are explained step by step on the Design System Platform: [${fw.setupTitle}](${PLATFORM}/learn/${fw.setup}).`,
		`Products of Deutsche Bahn also need the DB Theme with the brand colors, fonts and icons: [Add the DB Theme for DB products](${PLATFORM}/learn/db-theme-setup).`,
		'## Try it without a setup',
		`The [example projects](${PLATFORM}/learn/examples) open in StackBlitz, no local setup needed. Use them to try the components or to share a reproducible example in an issue.`,
		'## Versions',
		'This Storybook shows one release. The version dropdown next to each framework in the composition Storybook opens earlier releases. When you update across a Major version, check the [Migration Guides](https://design-system.deutschebahn.com/documentation/releases/migration-guides).',
		'## Design guidelines',
		`When and how to use a component is documented on the [Design System Platform](${PLATFORM}/components/overview).`
	].join('\n\n') + '\n';

const components = process.argv.slice(2);
if (components.length === 0) {
	throw new Error('[overviews] pass at least one component, e.g. "button"');
}
const allMeta = JSON.parse(
	read(join(import.meta.dirname, 'components.json'))
) as Record<string, ComponentMeta>;

for (const name of components) {
	const meta = allMeta[name];
	if (!meta) {
		throw new Error(`[overviews] ${name} is missing in components.json`);
	}
	for (const fw of FRAMEWORKS) {
		const dir = join(STORYBOOKS, fw.storybook, 'src/overview', name);
		const firstExample = getExamples(name, fw.examplesFrom)[0].file;
		write(
			join(dir, `${name}.overview.mdx`),
			buildOverviewMdx(name, meta, fw)
		);
		write(
			join(dir, `${name}.overview.stories.${fw.storiesExt}`),
			buildStories(name, meta, fw, firstExample)
		);
	}
}
for (const fw of FRAMEWORKS) {
	write(
		join(STORYBOOKS, fw.storybook, 'src/index.mdx'),
		buildGettingStarted(fw)
	);
}
