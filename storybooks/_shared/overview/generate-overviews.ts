/**
 * PROTOTYPE – generates the component overview pages for every Storybook.
 *
 * Writes per component:
 * - `<framework>-storybook/src/overview/<name>/<name>.overview.mdx` and the
 *   CSF file it attaches to, for React, Angular, Vue, HTML and Web Components
 * - `_storybook/src/components/<name>.overview.mdx`, the entry page in the
 *   composition Storybook that leads to the framework overviews
 * - the "Getting Started" page of every framework Storybook
 *
 * Inputs (one source per kind of content):
 * - `components.json` next to this file: summary, status, accessibility review
 * - `packages/components/src/components/<name>/docs/*.md`: usage per
 *   framework, accessibility, migration
 * - the generated example stories (`pnpm --filter @db-ux/core-components run
 *   generate:stories` must have run): story groups and story names
 * - `<name>.lite.tsx` and `output/stencil/dist/web-types.json`: attributes for
 *   HTML and Web Components
 *
 * Usage: node storybooks/_shared/overview/generate-overviews.ts button [...]
 *
 * The output is committed. If the approach is adopted, this moves into the
 * Mitosis Storybook plugin and runs with `generate:stories`.
 */
