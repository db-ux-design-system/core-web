const pascal = (value: string): string =>
	value.replaceAll(/(^|[-_ ])(\w)/g, (_, __, char: string) =>
		char.toUpperCase()
	);

const escapeCell = (value: string): string =>
	value
		.replaceAll(/\s*\n\s*/g, ' ')
		// Backslash first, so it cannot cancel the escape of a following `|`.
		.replaceAll('\\', '\\\\')
		.replaceAll('|', String.raw`\|`)
		.replaceAll(/[{}<>]/g, (char) => `&#${char.codePointAt(0)};`);

type ExampleGroup = {
	file: string;
	/** Component segment of the story title, e.g. `DBCustomHeading`. */
	componentTitle: string;
	title: string;
	id: string;
	stories: string[];
};

/** Story groups of a component, read from the generated example stories. */
const getExamples = (name: string, storybook: string): ExampleGroup[] => {
	const dir = join(STORYBOOKS, storybook, 'src/components', name, 'examples');
	if (!existsSync(dir)) {
		throw new Error(
			`[overviews] ${dir} is missing – run generate:stories first`
		);
	}
	return readdirSync(dir)
		.filter((file) => /\.example\.stories\.tsx?$/.test(file))
		.map((file) => {
			const source = read(join(dir, file));
			// `Components/DBHeading/Default`: component and group title.
			const [, componentTitle, title] =
				/title:\s*'[^']*\/([^'/]+)\/([^'/]+)'/.exec(source) ?? [];
			if (!title) {
				throw new Error(`[overviews] no title in ${file}`);
			}
			const stories = [
				...source.matchAll(/^export const (\w+): Story/gm)
			].map((match) => match[1]);
			// Same rule as Storybook's `sanitize` for story ids, so the links
			// "Open the … examples" match (e.g. "Example - Length" ->
			// "example-length").
			const id = title
				.toLowerCase()
				.replaceAll(/[^\da-z]+/g, '-')
				.replaceAll(/^-+|-+$/g, '');
			return {
				file: file.replace(/\.tsx?$/, ''),
				componentTitle,
				title,
				id,
				stories
			};
		})
		.toSorted((a, b) =>
			a.id === 'variant'
				? -1
				: b.id === 'variant'
					? 1
					: a.title.localeCompare(b.title)
		);
};

