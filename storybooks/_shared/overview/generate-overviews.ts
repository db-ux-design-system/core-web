const { values: options, positionals } = parseArgs({
	allowPositionals: true,
	options: {
		storybook: { type: 'string' },
		// Prints main components and their parts (meta.ts) and exits.
		structure: { type: 'boolean' }
	}
});

if (options.structure) {
	const { main, parts } = getStructure();
	for (const name of main) {
		const hasExamples =
			existsSync(
				join(
					STORYBOOKS,
					'react-storybook/src/components',
					name,
					'examples'
				)
			) && getExamples(name, 'react-storybook').length > 0;
		console.log(
			`${name}${hasExamples ? '' : ' (no examples)'}${parts[name] ? ` <- ${parts[name].join(', ')}` : ''}`
		);
	}

	// eslint-disable-next-line unicorn/no-process-exit -- this file is a CLI script
	process.exit(0);
}
const components =
	positionals.length > 0
		? positionals
		: getStructure().main.filter((name) => !EXCLUDE.includes(name));
const targets = options.storybook
	? FRAMEWORKS.filter((fw) => fw.storybook === options.storybook)
	: FRAMEWORKS;
if (targets.length === 0) {
	throw new Error(
		`[overviews] unknown Storybook "${options.storybook}", use one of ${FRAMEWORKS.map((fw) => fw.storybook).join(', ')}`
	);
}

for (const name of components) {
	const meta = getComponentMeta(name);
	for (const fw of targets) {
		const dir = join(STORYBOOKS, fw.storybook, 'src/overview', name);
		const firstExample = getExampleGroups(name, fw)[0]?.file;
		if (!firstExample) {
			console.warn(
				`[overviews] ${name} has no examples in ${fw.examplesFrom}: no overview page`
			);
			continue;
		}

		write(
			join(dir, `${name}.overview.mdx`),
			buildOverviewMdx(name, meta, fw)
		);
		write(
			join(dir, `${name}.overview.stories.${fw.storiesExt}`),
			buildStories(name, meta, fw, firstExample)
		);
	}
}
for (const fw of targets) {
	write(
		join(STORYBOOKS, fw.storybook, 'src/index.mdx'),
		buildGettingStarted(fw)
	);
}
