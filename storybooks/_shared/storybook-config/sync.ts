/**
 * PROTOTYPE – copies the shared Storybook config files into every framework
 * Storybook (`.storybook/mode.ts`, `.storybook/autodocs-page.mdx`,
 * `.storybook/source-imports.ts` and the theme files `theme.ts`,
 * `theme-values.json`, `manager.ts`) and writes the two head files:
 *
 * - `manager-head.html`: favicon and fonts (manager-head.html of this folder)
 *   plus manager.css with the `--db-sb-*` values from theme-values.json
 * - `preview-head.html`: docs.css plus docs-anchor.js (deep links to a
 *   section of a docs page)
 *
 * Both CSS files are CSS escape hatches, which Storybook documents in these
 * two head files. The composition Storybook gets the theme and head files
 * only.
 *
 * Copies instead of imports, because the Angular build only compiles files
 * inside its own project. Run after editing a file in this folder:
 *
 *   node storybooks/_shared/storybook-config/sync.ts
 */
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const STORYBOOKS = resolve(import.meta.dirname, '..', '..');
const THEME_FILES = ['theme.ts', 'theme-values.json', 'manager.ts'];
const FILES = [
	'mode.ts',
	'autodocs-page.mdx',
	'source-imports.ts',
	...THEME_FILES
];
const TARGETS = [
	'react-storybook',
	'angular-storybook',
	'vue-storybook',
	'stencil-storybook',
	'html-storybook'
];

// The composition Storybook has no component stories, it only needs the
// theme and the head files.
const COMPOSITION = { target: '_storybook', files: THEME_FILES };

const read = (file: string) =>
	readFileSync(join(import.meta.dirname, file), 'utf8');

const generatedNote = (sources: string) =>
	`<!-- Generated by storybooks/_shared/storybook-config/sync.ts from ${sources}. Do not edit. -->\n`;

/** `brandLogo` -> `--db-sb-brand-logo`; only plain CSS values. */
const themeVariables = (): string => {
	const values = JSON.parse(read('theme-values.json')) as Record<
		string,
		string
	>;
	return Object.entries(values)
		.filter(([key]) => !key.startsWith('font') && key !== 'brandLogo')
		.map(
			([key, value]) =>
				`--db-sb-${key.replaceAll(/[A-Z\d]+/g, (part) => `-${part.toLowerCase()}`)}: ${value};`
		)
		.join('\n');
};

/** Formatted like the rest of the repository (prettier --check). */
const formatHtml = async (content: string): Promise<string> => {
	const filepath = join(STORYBOOKS, 'react-storybook/.storybook/head.html');
	const options = await resolveConfig(filepath, { editorconfig: true });
	return format(content, { ...options, filepath });
};

const heads = {
	'manager-head.html': await formatHtml(
		[
			generatedNote(
				'manager-head.html, manager.css and theme-values.json'
			),
			read('manager-head.html').trimEnd(),
			'<style data-db-theme="manager">',
			`:root {\n${themeVariables()}\n}\n`,
			read('manager.css').trimEnd(),
			'</style>'
		].join('\n')
	),
	'preview-head.html': await formatHtml(
		[
			generatedNote('docs.css and docs-anchor.js'),
			'<style data-db-theme="docs">',
			read('docs.css').trimEnd(),
			'</style>',
			'<script data-db-theme="docs-anchor">',
			read('docs-anchor.js').trimEnd(),
			'</script>'
		].join('\n')
	)
};

for (const { target, files } of [
	...TARGETS.map((name) => ({ target: name, files: FILES })),
	COMPOSITION
]) {
	const directory = join(STORYBOOKS, target, '.storybook');
	for (const file of files) {
		copyFileSync(join(import.meta.dirname, file), join(directory, file));
		console.log(`[storybook-config] ${target}/.storybook/${file}`);
	}

	for (const [file, content] of Object.entries(heads)) {
		writeFileSync(join(directory, file), content);
		console.log(`[storybook-config] ${target}/.storybook/${file}`);
	}
}
